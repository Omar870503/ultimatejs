let a = 10;
console.log(a > 5, "Mayor que"); // Mayor que
console.log(a < 5, "Menor que"); // Menor que
console.log(a >= 10, "Mayor o igual que"); // Mayor o igual que
console.log(a <= 10, "Menor o igual que"); // Menor o igual que
console.log(a == 10, "Igualdad"); // Igualdad
console.log(a != 10, "Desigualdad"); // Desigualdad
console.log(a == "10", "Igualdad con coerción de tipo"); // Igualdad con coerción de tipo
console.log(a === "10", "Igualdad estricta"); // Igualdad estricta
console.log(a !== "10", "Desigualdad estricta"); // Desigualdad estricta